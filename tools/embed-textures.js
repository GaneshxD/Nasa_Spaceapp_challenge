/* Packs the NASA Earth images into assets/textures.js as data URLs.
 *
 * Why: browsers refuse to load image files into WebGL when a page is opened
 * straight from disk (file://). Embedding them in a script lets the game run
 * by double-clicking index.html, with no web server.
 *
 * Run after replacing an image in assets/img:  node tools/embed-textures.js
 */
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'assets');
const files = {
  earthDay: 'img/earth_day_nasa_gibs_blue_marble.jpg',
  earthNight: 'img/earth_night_nasa_gibs_black_marble.jpg'
};
let out = '/* Generated by tools/embed-textures.js. Do not edit by hand.\n' +
  ' * NASA GIBS imagery: Blue Marble Next Generation (day) and VIIRS Black Marble (night). Public domain. See CREDITS.md. */\n' +
  '(function (root) {\n  var RG = (root.RG = root.RG || {});\n  RG.TEXTURES = {\n';
out += Object.entries(files).map(([key, file]) => {
  const b64 = fs.readFileSync(path.join(dir, file)).toString('base64');
  return `    ${key}: 'data:image/jpeg;base64,${b64}'`;
}).join(',\n');
out += '\n  };\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
fs.writeFileSync(path.join(dir, 'textures.js'), out);
console.log('Wrote assets/textures.js', (out.length / 1024).toFixed(0) + ' KB');
